def main():
    with open(JSON_PATH, 'r', encoding='utf-8') as f:
        tools = json.load(f)

    hit = 0
    for t in tools:
        tid = t.get('id')
        if tid in NOTES:
            t['editorNote'] = NOTES[tid]
            hit += 1

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(tools, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f'注入编辑点评 {hit} 条 / NOTES 共 {len(NOTES)} 条 / 工具总数 {len(tools)}')
    miss = [k for k in NOTES if k not in {t.get("id") for t in tools}]
    if miss:
        print('⚠️ 以下 id 不在 tools.json 中:', miss)


if __name__ == '__main__':
    main()
