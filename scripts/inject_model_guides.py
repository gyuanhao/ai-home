    hit = 0
    for m in models:
        mid = m.get('id')
        if mid in GUIDES:
            m['guide'] = GUIDES[mid]
            hit += 1

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(models, f, ensure_ascii=False, indent=2)
        f.write('\n')

    have = sum(1 for m in models if m.get('guide'))
    print(f'本批注入 {hit} 条 / GUIDES 共 {len(GUIDES)} 条')
    print(f'模型总数 {len(models)}，现有 guide 的模型 {have} 个，仍缺 {len(models) - have} 个')
    miss = [k for k in GUIDES if k not in {m.get("id") for m in models}]
    if miss:
        print('⚠️ 以下 id 不在 models.json 中:', miss)


